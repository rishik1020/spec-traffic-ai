def write_data_yaml(root: Path, path: Path | None = None) -> Path:
    """Generate the data.yaml ultralytics reads, from SENTI_CLASSES.

    Generated rather than hand-written on purpose: a hand-edited class list that
    disagrees with SENTI_CLASSES produces a model whose class 6 is not what the
    inference layer thinks class 6 is, and nothing anywhere will tell you.
    """
    path = path or (root / "data.yaml")

    # Never overwrite someone else's class list. Doing so is silent and
    # unrecoverable-looking: the labels still parse, training still runs, and
    # the resulting model is wrong in a way no error message mentions.
    existing = read_yaml_names(path)
    if existing is not None and not _is_generated_by_us(path):
        if list(existing) != list(SENTI_CLASSES):
            raise SystemExit(
                f"refusing to overwrite {path}\n"
                f"  it declares {existing}, we use {list(SENTI_CLASSES)}.\n"
                f"  Run `remap` to convert the labels onto our class list first."
            )

    names = "\n".join(f"  {i}: {n}" for i, n in enumerate(SENTI_CLASSES))
    path.write_text(
        f"{GENERATED_MARKER} -- do not hand-edit.\n"
        "# The class list mirrors senti_traffic_ml.SENTI_CLASSES; change it there.\n"
        f"path: {root.resolve().as_posix()}\n"
        "train: images/train\n"
        "val: images/val\n"
        f"nc: {len(SENTI_CLASSES)}\n"
        "names:\n"
        f"{names}\n",
        encoding="utf-8",
    )
    return path


# ---------------------------------------------------------------------------
# 3b. REMAP -- fold a foreign dataset onto SENTI_CLASSES
# ---------------------------------------------------------------------------


def remap_dataset(src: Path, dst: Path, extra_map: dict[str, str],
                  drop_unmapped: bool, dry_run: bool = True) -> None:
    """Rewrite a dataset's label IDs from its own class list onto ours.

    Every public dataset numbers its classes differently -- IDD, DriveIndia and
    a plates set all use `0` for three unrelated things. This is the one place
    that difference gets resolved, by NAME, before any training happens.

    Images are hard-linked where the filesystem allows it (instant, no extra
    disk) and copied otherwise. The source tree is never modified.
    """
    src_names = read_yaml_names(src / "data.yaml")
    if src_names is None:
        raise SystemExit(
            f"no data.yaml with a names: list under {src}\n"
            f"  Without it there is no way to know what the label IDs mean."
        )

    # source id -> our id, resolved by name
    id_map: dict[int, int] = {}
    unmapped: list[str] = []
    for src_id, raw in enumerate(src_names):
        override = extra_map.get(raw.strip().lower())
        name = override or canonical_class(raw)
        if name is None or name not in SENTI_CLASSES:
            unmapped.append(raw)
            continue
        id_map[src_id] = SENTI_CLASSES.index(name)

    print(f"source classes: {src_names}")
    for src_id, our_id in sorted(id_map.items()):
        print(f"  {src_id:>2} {src_names[src_id]:<20} -> {our_id:>2} {SENTI_CLASSES[our_id]}")
    for raw in unmapped:
        print(f"  -- {raw:<20} -> DROPPED (no equivalent in SENTI_CLASSES)")

    if unmapped and not drop_unmapped:
        raise SystemExit(
            f"\n{len(unmapped)} class(es) have no equivalent: {unmapped}\n"
            f"  Either pass --map '{unmapped[0]}=motorcycle' style overrides,\n"
            f"  or --drop-unmapped to discard those boxes. Refusing to guess.\n"
            f"  NOTE: dropping a class turns its objects into background, which\n"
            f"  actively teaches the model to ignore them. That is right for\n"
            f"  number plates (a separate detector) and wrong for, say, a\n"
            f"  'rider' class you actually care about."
        )
    if not id_map:
        raise SystemExit("nothing to remap: no source class matched SENTI_CLASSES")

    total_in = total_out = images_done = 0
    for split in ("train", "val"):
        for image in _images_in(src, split):
            label_src = _label_path(image, src, split)
            kept: list[str] = []
            if label_src.exists():
                for line in label_src.read_text(encoding="utf-8",
                                                errors="replace").splitlines():
                    parts = line.split()
                    if len(parts) != 5:
                        continue
                    total_in += 1
                    src_id = int(float(parts[0]))
                    if src_id not in id_map:
                        continue
                    kept.append(" ".join([str(id_map[src_id]), *parts[1:]]))
                    total_out += 1

            images_done += 1
            if dry_run:
                continue

            (dst / "images" / split).mkdir(parents=True, exist_ok=True)
            (dst / "labels" / split).mkdir(parents=True, exist_ok=True)
            image_dst = dst / "images" / split / image.name
            if not image_dst.exists():
                try:
                    import os

                    os.link(image, image_dst)      # same volume: free
                except OSError:
                    import shutil

                    shutil.copy2(image, image_dst)
            # Always write the .txt, even when empty: an absent label and an
            # empty one mean the same thing to YOLO, but an explicit empty file
            # documents that we looked and there was nothing to keep.
            (dst / "labels" / split / (image.stem + ".txt")).write_text(
                "\n".join(kept) + ("\n" if kept else ""), encoding="utf-8")

    verb = "would write" if dry_run else "wrote"
    print(f"\n{verb} {images_done} image(s); boxes {total_in} -> {total_out} "
          f"({total_in - total_out} dropped)")

    if unmapped and total_in > total_out:
        share = 100.0 * (total_in - total_out) / total_in
        shown = ", ".join(unmapped[:4]) + ("..." if len(unmapped) > 4 else "")
        print(
            f"\n[warn] {share:.0f}% of boxes were dropped, from: {shown}\n"
            f"       Those objects are now unlabelled *background* in images that\n"
            f"       still contain them, which actively trains the model to ignore\n"
            f"       them. Fine for scenery; check the list above for anything a\n"
            f"       rule depends on and re-run with --map 'THEIRS=OURS'."
        )
    if dry_run:
        print("dry run -- pass --apply to write")
    else:
        write_data_yaml(dst)
        print(f"remapped dataset ready: {dst}")
        print(f"next: python senti_traffic_train.py check --data {dst}")


