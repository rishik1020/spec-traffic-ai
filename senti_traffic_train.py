def split_dataset(root: Path, val_fraction: float, seed: int = 0,
                  dry_run: bool = True) -> None:
    """Move a fraction of images/train (and their labels) into images/val.

    Deterministic given `seed`, so re-running does not reshuffle what is
    already split. Defaults to a dry run -- pass --apply to actually move.
    """
    train_images = _images_in(root, "train")
    if not train_images:
        raise SystemExit(f"nothing to split: no images under {root / 'images' / 'train'}")

    existing_val = len(_images_in(root, "val"))
    if existing_val:
        print(f"[note] images/val already holds {existing_val} image(s); "
              f"splitting more on top of it")

    rng = random.Random(seed)
    shuffled = sorted(train_images)
    rng.shuffle(shuffled)
    cut = int(len(shuffled) * val_fraction)
    moving = shuffled[:cut]

    if not moving:
        raise SystemExit(f"val_fraction {val_fraction} rounds to zero images")

    print(f"{'would move' if dry_run else 'moving'} {len(moving)} of "
          f"{len(train_images)} image(s) into val ({val_fraction:.0%})")
    if dry_run:
        print("dry run -- pass --apply to perform the move")
        return

    (root / "images" / "val").mkdir(parents=True, exist_ok=True)
    (root / "labels" / "val").mkdir(parents=True, exist_ok=True)

    for image in moving:
        image.rename(root / "images" / "val" / image.name)
        label = _label_path(image, root, "train")
        if label.exists():
            label.rename(root / "labels" / "val" / label.name)

    print("done")


