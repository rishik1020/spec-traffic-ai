"""
senti_traffic_train.py
======================
Senti Traffic -- fine-tuning the detector on Indian footage.

senti_traffic_ml.py deliberately does no training: it loads weights and returns
Detections. This file is the other half -- it turns a labelled dataset into the
weights that file loads.

WHY THIS EXISTS
---------------
COCO has no auto-rickshaw class. Three-wheelers are a large share of Indian
traffic and pretrained YOLO scatters them across car / truck / motorcycle
depending on the angle. No amount of threshold tuning fixes that; the weights
have never seen the object. The only fix is fine-tuning on Indian footage with
`auto_rickshaw` as a real class.

The class list lives in senti_traffic_ml.SENTI_CLASSES and is written into
data.yaml from there, so the trained model and the inference layer cannot drift
apart.

DATASET LAYOUT (standard YOLO format)
-------------------------------------
    dataset/
      images/train/frame_0001.jpg      labels/train/frame_0001.txt
      images/val/frame_0100.jpg        labels/val/frame_0100.txt

Each label file is one line per object, normalised to 0-1:

    <class_id> <x_center> <y_center> <width> <height>

class_id is the INDEX INTO SENTI_CLASSES:

    0 person   1 bicycle   2 car   3 motorcycle   4 bus   5 truck   6 auto_rickshaw

An empty .txt means "this image genuinely contains none of our classes" -- that
is a valid and useful training sample, not a mistake. A *missing* .txt is a
different thing entirely: YOLO reads it as an empty label too, so an
unannotated image silently teaches the model that the vehicles in it are
background. `check` flags that.

USAGE
-----
    python senti_traffic_train.py check   --data path/to/dataset
    python senti_traffic_train.py train   --data path/to/dataset --epochs 100
    python senti_traffic_train.py val     --weights runs/senti/weights/best.pt --data path/to/dataset
    python senti_traffic_train.py export  --weights runs/senti/weights/best.pt

Run `check` first. It is fast, it is read-only, and every hour it costs you up
front is several hours of training it saves.
"""

from __future__ import annotations

import argparse
import collections
import random
import sys
from pathlib import Path
from typing import Optional

from senti_traffic_ml import SENTI_CLASSES, canonical_class

GENERATED_MARKER = "# GENERATED by senti_traffic_train.py"

IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".bmp", ".webp", ".tif", ".tiff"}

# Recommended split when you have one undivided pile of images.
DEFAULT_VAL_FRACTION = 0.2


# ---------------------------------------------------------------------------
# 1. DATASET INSPECTION
# ---------------------------------------------------------------------------


def _is_generated_by_us(path: Path) -> bool:
    """True if we wrote this data.yaml, so its names are SENTI_CLASSES already."""
    if not path.is_file():
        return False
    head = path.read_text(encoding="utf-8", errors="replace")[:200]
    return GENERATED_MARKER in head


def read_yaml_names(path: Path) -> Optional[list[str]]:
    """Pull the `names:` list out of an existing data.yaml, or None.

    Uses PyYAML when available (ultralytics depends on it, so it usually is)
    and falls back to a deliberately dumb line parser that handles the two
    shapes ultralytics writes: `0: name` mappings and `- name` lists.
    """
    if not path.is_file():
        return None

    text = path.read_text(encoding="utf-8", errors="replace")
    try:
        import yaml  # noqa: PLC0415 -- optional, resolved at call time

        data = yaml.safe_load(text) or {}
        names = data.get("names")
        if isinstance(names, dict):
            return [str(names[k]) for k in sorted(names, key=lambda k: int(k))]
        if isinstance(names, list):
            return [str(n) for n in names]
        return None
    except ImportError:
        pass

    names, inside = [], False
    for raw in text.splitlines():
        if raw.strip().startswith("#"):
            continue
        if raw.rstrip().startswith("names:"):
            inside = True
            continue
        if inside:
            if raw[:1].strip() and not raw.startswith((" ", "\t", "-")):
                break                      # dedented: names block is over
            item = raw.strip()
            if not item:
                continue
            if item.startswith("- "):
                names.append(item[2:].strip())
            elif ":" in item:
                names.append(item.split(":", 1)[1].strip())
    return names or None


def _label_path(image_path: Path, root: Path, split: str) -> Path:
    """images/<split>/x.jpg -> labels/<split>/x.txt"""
    return root / "labels" / split / (image_path.stem + ".txt")


def _images_in(root: Path, split: str) -> list[Path]:
    directory = root / "images" / split
    if not directory.is_dir():
        return []
    return sorted(
        p for p in directory.iterdir()
        if p.is_file() and p.suffix.lower() in IMAGE_SUFFIXES
    )


class DatasetReport:
    """What we found, and whether it is safe to train on."""

    def __init__(self) -> None:
        self.splits: dict[str, int] = {}
        self.class_counts: collections.Counter = collections.Counter()
        self.unlabelled: list[Path] = []
        self.empty_labels: list[Path] = []
        self.orphan_labels: list[Path] = []
        self.errors: list[str] = []          # hard stops
        self.warnings: list[str] = []        # train anyway, but know about it
        self.foreign_names: Optional[list[str]] = None   # dataset's own class list

    @property
    def total_images(self) -> int:
        return sum(self.splits.values())

    @property
    def total_boxes(self) -> int:
        return sum(self.class_counts.values())

    @property
    def ok(self) -> bool:
        return not self.errors


def check_dataset(root: Path, strict: bool = False) -> DatasetReport:
    """Validate a YOLO dataset without loading a single image pixel.

    Catches the failure modes that otherwise show up as a model that trains
    "successfully" for six hours and then detects nothing.
    """
    report = DatasetReport()

    if not root.is_dir():
        report.errors.append(f"dataset root does not exist: {root}")
        return report

    # A dataset that ships its own data.yaml was labelled against ITS class
    # list, not ours. Class IDs are just positions, so a plates dataset with
    # `0: number_plate` is bit-for-bit indistinguishable from `0: person` --
    # train on it blind and every plate box teaches the model what a pedestrian
    # looks like. Nothing crashes; the model just quietly comes out wrong.
    existing = read_yaml_names(root / "data.yaml")
    if existing is not None and not _is_generated_by_us(root / "data.yaml"):
        report.foreign_names = existing
        canon = [canonical_class(n) for n in existing]
        if list(existing) != list(SENTI_CLASSES):
            unknown = [n for n, c in zip(existing, canon) if c is None]
            report.errors.append(
                f"{root / 'data.yaml'} declares a different class list:\n"
                f"           theirs: {existing}\n"
                f"           ours:   {list(SENTI_CLASSES)}\n"
                f"         Class IDs are positions in that list, so training "
                f"this as-is silently relabels every box"
                + (f" (unmapped: {unknown})" if unknown else "")
                + ".\n         Remap the label files first -- see `remap`."
            )

    for split in ("train", "val"):
        images = _images_in(root, split)
        report.splits[split] = len(images)

        label_dir = root / "labels" / split
        seen_labels: set[Path] = set()

        for image in images:
            label = _label_path(image, root, split)
            if not label.exists():
                # NOT the same as an empty file: YOLO treats both as "no
                # objects here", so a forgotten annotation actively teaches the
                # model that these vehicles are background.
                report.unlabelled.append(image)
                continue

            seen_labels.add(label.resolve())
            lines = [
                ln.strip()
                for ln in label.read_text(encoding="utf-8", errors="replace").splitlines()
                if ln.strip()
            ]
            if not lines:
                report.empty_labels.append(label)
                continue

            for lineno, line in enumerate(lines, 1):
                parts = line.split()
                if len(parts) != 5:
                    report.errors.append(
                        f"{label}:{lineno}: expected 5 fields "
                        f"(class cx cy w h), got {len(parts)}"
                    )
                    continue
                try:
                    cls_id = int(float(parts[0]))
                    cx, cy, bw, bh = (float(v) for v in parts[1:])
                except ValueError:
                    report.errors.append(f"{label}:{lineno}: non-numeric value")
                    continue

                if not 0 <= cls_id < len(SENTI_CLASSES):
                    report.errors.append(
                        f"{label}:{lineno}: class id {cls_id} outside 0..{len(SENTI_CLASSES) - 1}. "
                        f"The dataset was probably exported against a different class list."
                    )
                    continue

                # YOLO wants normalised coordinates. Absolute pixel values are
                # the single most common export mistake and they train to
                # garbage rather than crashing.
                if not all(0.0 <= v <= 1.0 for v in (cx, cy, bw, bh)):
                    report.errors.append(
                        f"{label}:{lineno}: coordinates outside 0-1 "
                        f"({cx:.1f} {cy:.1f} {bw:.1f} {bh:.1f}). "
                        f"These look like pixels -- YOLO needs them normalised."
                    )
                    continue
                if bw <= 0 or bh <= 0:
                    report.errors.append(f"{label}:{lineno}: zero-area box")
                    continue

                report.class_counts[SENTI_CLASSES[cls_id]] += 1

        if label_dir.is_dir():
            for label in label_dir.glob("*.txt"):
                if label.resolve() not in seen_labels:
                    report.orphan_labels.append(label)

    # -- judgement ----------------------------------------------------------

    if report.splits.get("train", 0) == 0:
        report.errors.append(
            f"no training images found under {root / 'images' / 'train'}"
        )
    if report.splits.get("val", 0) == 0:
        report.errors.append(
            f"no validation images found under {root / 'images' / 'val'}. "
            f"Without a val split there is no way to tell learning from "
            f"memorising -- use `split` to carve one out."
        )

    if report.unlabelled:
        message = (
            f"{len(report.unlabelled)} image(s) have no label file. YOLO reads "
            f"those as 'contains nothing', which trains the model to ignore "
            f"whatever is in them."
        )
        (report.errors if strict else report.warnings).append(message)
    if report.orphan_labels:
        report.warnings.append(
            f"{len(report.orphan_labels)} label file(s) have no matching image "
            f"(ignored during training)"
        )

    for name in SENTI_CLASSES:
        count = report.class_counts[name]
        if count == 0:
            report.warnings.append(
                f"class '{name}' has zero examples -- the model cannot learn it, "
                f"and TrafficDetector.missing_classes will report it at runtime"
            )
        elif count < 50:
            report.warnings.append(
                f"class '{name}' has only {count} example(s); expect unreliable "
                f"detections below a few hundred"
            )

    if report.class_counts:
        most = report.class_counts.most_common()
        top_name, top_count = most[0]
        rare = [(n, c) for n, c in most if c > 0][-1]
        if rare[1] and top_count / rare[1] > 20:
            report.warnings.append(
                f"heavy class imbalance: '{top_name}' has {top_count} boxes vs "
                f"'{rare[0]}' with {rare[1]} ({top_count / rare[1]:.0f}x). The "
                f"rare class will be under-detected; consider more footage of it."
            )

    return report


def print_report(report: DatasetReport) -> None:
    print(f"\nimages   train={report.splits.get('train', 0)}  "
          f"val={report.splits.get('val', 0)}  total={report.total_images}")
    print(f"boxes    {report.total_boxes}")

    if report.class_counts:
        if report.foreign_names:
            # Without this the table reads as fact. It is not: these counts are
            # the dataset's own IDs looked up in OUR list, which is precisely
            # the mistranslation the error below is about.
            print(f"\nper class -- MISREAD ON PURPOSE, see the error below."
                  f"\n(IDs interpreted as {list(SENTI_CLASSES)},"
                  f"\n but this dataset labelled them {report.foreign_names})")
        else:
            print("\nper class:")
        width = max(len(n) for n in SENTI_CLASSES)
        for name in SENTI_CLASSES:
            count = report.class_counts[name]
            share = 100.0 * count / report.total_boxes if report.total_boxes else 0.0
            bar = "#" * int(share / 2)
            flag = "" if count else "   <- absent"
            print(f"  {name:<{width}}  {count:6d}  {share:5.1f}%  {bar}{flag}")

    if report.empty_labels:
        print(f"\n{len(report.empty_labels)} deliberately empty label(s) "
              f"(valid background samples)")

    for warning in report.warnings:
        print(f"\n[warn]  {warning}")
    for error in report.errors:
        print(f"\n[ERROR] {error}")

    print("\n" + ("dataset looks trainable" if report.ok
                  else "FIX THE ERRORS ABOVE BEFORE TRAINING"))


