def main() -> None:
    ap = argparse.ArgumentParser(
        description="Senti Traffic -- dataset checks and fine-tuning")
    sub = ap.add_subparsers(dest="command", required=True)

    c = sub.add_parser("check", help="validate a dataset (read-only, fast)")
    c.add_argument("--data", required=True, help="dataset root")
    c.add_argument("--strict", action="store_true",
                   help="treat unlabelled images as errors, not warnings")

    s = sub.add_parser("split", help="carve a val split out of images/train")
    s.add_argument("--data", required=True)
    s.add_argument("--val-fraction", type=float, default=DEFAULT_VAL_FRACTION)
    s.add_argument("--seed", type=int, default=0)
    s.add_argument("--apply", action="store_true",
                   help="actually move files (default is a dry run)")

    r = sub.add_parser("remap", help="convert a dataset's class IDs onto SENTI_CLASSES")
    r.add_argument("--src", required=True, help="source dataset root (with data.yaml)")
    r.add_argument("--dst", required=True, help="output dataset root")
    r.add_argument("--map", action="append", default=[], metavar="THEIRS=OURS",
                   help="force a mapping, e.g. --map 'vehicle fallback=car'")
    r.add_argument("--drop-unmapped", action="store_true",
                   help="discard boxes whose class has no equivalent")
    r.add_argument("--apply", action="store_true",
                   help="actually write (default is a dry run)")

    t = sub.add_parser("train", help="fine-tune on the dataset")
    t.add_argument("--data", required=True)
    t.add_argument("--weights", default="yolo11s.pt",
                   help="starting checkpoint (yolo11n/s/m/l)")
    t.add_argument("--epochs", type=int, default=100)
    t.add_argument("--imgsz", type=int, default=960,
                   help="train at the resolution you will infer at; 960 helps "
                        "distant two-wheelers")
    t.add_argument("--batch", type=int, default=-1, help="-1 = auto-fit to VRAM")
    t.add_argument("--device", default=None, help="cuda | cpu | 0")
    t.add_argument("--workers", type=int, default=4)
    t.add_argument("--project", default="runs")
    t.add_argument("--name", default="senti")
    t.add_argument("--patience", type=int, default=25,
                   help="early stop after N epochs without improvement")
    t.add_argument("--seed", type=int, default=0)
    t.add_argument("--degrees", type=float, default=5.0)
    t.add_argument("--no-flip", action="store_true",
                   help="disable horizontal flip (use for one-way-traffic scenes)")
    t.add_argument("--strict", action="store_true")

    v = sub.add_parser("val", help="score a checkpoint against the val split")
    v.add_argument("--weights", required=True)
    v.add_argument("--data", required=True)
    v.add_argument("--imgsz", type=int, default=960)
    v.add_argument("--device", default=None)

    e = sub.add_parser("export", help="export for deployment")
    e.add_argument("--weights", required=True)
    e.add_argument("--format", default="onnx")
    e.add_argument("--imgsz", type=int, default=960)
    e.add_argument("--half", action="store_true")

    args = ap.parse_args()

    if args.command == "check":
        report = check_dataset(Path(args.data).expanduser().resolve(), args.strict)
        print_report(report)
        sys.exit(0 if report.ok else 1)
    elif args.command == "split":
        split_dataset(Path(args.data).expanduser().resolve(),
                      args.val_fraction, args.seed, dry_run=not args.apply)
    elif args.command == "remap":
        overrides = {}
        for pair in args.map:
            if "=" not in pair:
                raise SystemExit(f"--map needs THEIRS=OURS, got {pair!r}")
            theirs, ours = pair.split("=", 1)
            ours = ours.strip()
            if ours not in SENTI_CLASSES:
                raise SystemExit(
                    f"--map target {ours!r} is not one of {list(SENTI_CLASSES)}")
            overrides[theirs.strip().lower()] = ours
        remap_dataset(Path(args.src).expanduser().resolve(),
                      Path(args.dst).expanduser().resolve(),
                      overrides, args.drop_unmapped, dry_run=not args.apply)
    elif args.command == "train":
        train(args)
    elif args.command == "val":
        validate(args)
    elif args.command == "export":
        export(args)


if __name__ == "__main__":
    main()
