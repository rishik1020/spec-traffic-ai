def train(args) -> None:
    from ultralytics import YOLO

    root = Path(args.data).expanduser().resolve()

    report = check_dataset(root, strict=args.strict)
    print_report(report)
    if not report.ok:
        raise SystemExit("\nrefusing to train on a dataset with errors "
                         "(use `check` to inspect, fix, then retry)")

    yaml_path = write_data_yaml(root)
    print(f"\n[senti] wrote {yaml_path}")

    model = YOLO(args.weights)
    print(f"[senti] fine-tuning {args.weights} -> {len(SENTI_CLASSES)} classes")

    model.train(
        data=str(yaml_path),
        epochs=args.epochs,
        imgsz=args.imgsz,
        batch=args.batch,
        device=args.device,
        workers=args.workers,
        project=args.project,
        name=args.name,
        exist_ok=True,
        patience=args.patience,
        seed=args.seed,

        # -- augmentation, tuned for traffic cameras ------------------------
        # A fixed pole sees one scene all day, so the model must not learn
        # "vehicles appear in the lower-left". Translation and scale jitter
        # matter more here than colour tricks.
        degrees=args.degrees,     # small: traffic cameras are roughly level
        translate=0.1,
        scale=0.5,                # distant vs near vehicles differ hugely in size
        fliplr=0.0 if args.no_flip else 0.5,
        mosaic=1.0,               # dense multi-vehicle scenes: this helps a lot
        close_mosaic=10,          # ...but turn it off at the end to match reality
        hsv_h=0.015,
        hsv_s=0.7,
        hsv_v=0.4,                # day/night and glare variation
    )

    best = Path(args.project) / args.name / "weights" / "best.pt"
    print(f"\n[senti] best weights: {best}")
    print(f"[senti] use them with: "
          f"python senti_traffic_ml.py --source clip.mp4 --weights {best}")


def validate(args) -> None:
    from ultralytics import YOLO

    root = Path(args.data).expanduser().resolve()
    yaml_path = write_data_yaml(root)

    model = YOLO(args.weights)
    metrics = model.val(data=str(yaml_path), imgsz=args.imgsz, device=args.device)

    print("\nper-class AP50 (higher is better; below ~0.5 is not deployable):")
    try:
        names = model.names
        for i, ap in enumerate(metrics.box.ap50):
            label = names[i] if isinstance(names, dict) else names[i]
            print(f"  {label:<16} {ap:.3f}")
    except Exception:  # noqa: BLE001 -- metrics shape varies across versions
        print("  (per-class breakdown unavailable; see the table above)")


def export(args) -> None:
    from ultralytics import YOLO

    model = YOLO(args.weights)
    out = model.export(format=args.format, imgsz=args.imgsz, half=args.half)
    print(f"[senti] exported -> {out}")


